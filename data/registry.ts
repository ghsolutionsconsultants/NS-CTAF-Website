export function findByCertId(idOrSlug: string): RegistryEntry | undefined {
  const norm = idOrSlug.trim().toLowerCase();
  return registry.find(
    (r) =>
      r.slug.toLowerCase() === norm ||
      r.certId.toLowerCase() === norm ||
      r.certId.toLowerCase().replace(/\//g, "-") === norm
  );
}
